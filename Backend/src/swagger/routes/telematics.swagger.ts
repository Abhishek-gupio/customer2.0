/**
 * @swagger
 * /api/v1/telematics/link/{vehicleId}:
 *   post:
 *     summary: Link App Instance to Vehicle
 *     tags: [Telematics]
 *     security:
 *       - bearerAuth: []
 *     parameters:
 *       - in: path
 *         name: vehicleId
 *         schema:
 *           type: string
 *         required: true
 *         description: ID of the vehicle to link
 *     requestBody:
 *       required: true
 *       content:
 *         application/json:
 *           schema:
 *             type: object
 *             required:
 *               - instanceId
 *             properties:
 *               instanceId:
 *                 type: string
 *                 description: Unique ID generated by the Mobile SDK
 *               platform:
 *                 type: string
 *                 enum: [ANDROID, IOS]
 *               deviceToken:
 *                 type: string
 *                 description: FCM/APNS Token for Push Notifications
 *     responses:
 *       200:
 *         description: Device linked successfully
 *       404:
 *         description: Vehicle not found
 */

