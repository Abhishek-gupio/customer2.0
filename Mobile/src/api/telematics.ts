import { api } from '../services/api';

export const telematicsApi = {
    /**
     * Registers a user with the backend, which forwards the request to Damoov
     * @param clientCustomId A unique identifier for the user (e.g. user ID or phone number)
     * @returns DeviceToken from Damoov
     */
    async registerUser(clientCustomId: string): Promise<string> {
        const response = await api.post<any>('/v1/telematics/register', {
            clientCustomId,
        });

        // The backend returns { success: true, data: { Result: { DeviceToken: "..." } } }
        return response?.data?.Result?.DeviceToken;
    },

    /**
     * Links a registered Telematics instance ID to the customer's vehicle
     * @param vehicleId The ID of the vehicle
     * @param instanceId The InstanceToken generated by the SDK
     * @param deviceToken The DeviceToken returned from the registration step
     * @param platform "ios" | "android"
     */
    async linkDevice(
        vehicleId: string,
        instanceId: string,
        deviceToken: string,
        platform: string
    ): Promise<any> {
        const response = await api.post<any>(`/v1/telematics/link/${vehicleId}`, {
            instanceId,
            deviceToken,
            platform,
        });
        return response;
    },

    /**
     * Get Trip History for a vehicle
     * @param vehicleId The ID of the vehicle
     */
    async getTrips(vehicleId: string): Promise<any> {
        const response = await api.get<any>(`/v1/telematics/${vehicleId}/trips`);
        return response;
    },

    /**
     * Get real-time AI driving coach advice
     * @param events Array of recent driving events (e.g. from the last few minutes)
     * @param context Additional context like current speed, weather, etc.
     */
    async getAiCoachAdvice(events: any[], context: any): Promise<string> {
        try {
            const response = await api.post<any>('/v1/ai/coach', {
                events,
                context,
            });
            return response?.data?.advice || "Keep driving safely.";
        } catch (error) {
            console.error("AI Coach API error:", error);
            return "Drive safely and maintain a steady speed.";
        }
    }
};
